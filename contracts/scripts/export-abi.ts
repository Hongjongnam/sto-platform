// Writes the ABIs the backend needs into backend/src/chain/abi.generated.ts.
//
//   npx hardhat build && node scripts/export-abi.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const TARGET = join(ROOT, "..", "backend", "src", "chain", "abi.generated.ts");

const CONTRACTS: Record<string, string> = {
  IdentityRegistry: "identity/IdentityRegistry.sol",
  SecurityToken: "token/SecurityToken.sol",
  ModularCompliance: "compliance/ModularCompliance.sol",
  MaxBalanceModule: "compliance/modules/MaxBalanceModule.sol",
  MaxHoldersModule: "compliance/modules/MaxHoldersModule.sol",
  CountryAllowModule: "compliance/modules/CountryAllowModule.sol",
  DvPSettlement: "settlement/DvPSettlement.sol",
  DividendDistributor: "corporate-actions/DividendDistributor.sol",
  RedemptionManager: "corporate-actions/RedemptionManager.sol",
  USDC: "mocks/USDC.sol",
};

const lines = [
  "// Generated by contracts/scripts/export-abi.ts. Do not edit.",
  "/* oxlint-disable */",
  "",
];
for (const [name, source] of Object.entries(CONTRACTS)) {
  const artifact = JSON.parse(readFileSync(join(ROOT, "artifacts", "contracts", source, `${name}.json`), "utf8"));
  lines.push(`export const ${name}Abi = ${JSON.stringify(artifact.abi)} as const;`, "");
}
lines.push(
  "export const ABIS = {",
  ...Object.keys(CONTRACTS).map((name) => `  ${name}: ${name}Abi,`),
  "} as const;",
  "",
  "export type ContractName = keyof typeof ABIS;",
  "",
);

writeFileSync(TARGET, lines.join("\n"));
console.log(`wrote ${Object.keys(CONTRACTS).length} ABIs to ${TARGET}`);
