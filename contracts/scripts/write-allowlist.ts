// Writes infra/besu/permissions_config.toml: the accounts the nodes accept transactions from.
//
//   node scripts/write-allowlist.ts [count]
//
// Accounts are derived from the development mnemonic. The first twenty hold roles or act in
// the scripts; the rest are the custodial investor wallets the backend hands out, so the
// count bounds how many wallets the backend can create on this network.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { HDNodeWallet, Mnemonic } from "ethers";

const MNEMONIC = "test test test test test test test test test test test junk";
const count = Number(process.argv[2] ?? 1020);
const mnemonic = Mnemonic.fromPhrase(MNEMONIC);
const accounts = Array.from({ length: count }, (_, index) => HDNodeWallet.fromMnemonic(mnemonic, `m/44'/60'/0'/0/${index}`).address);

const target = join(import.meta.dirname, "..", "..", "infra", "besu", "permissions_config.toml");
writeFileSync(
  target,
  `# Accounts allowed to submit transactions. Everything else is rejected by the nodes.
# Generated by contracts/scripts/write-allowlist.ts from the first ${count} accounts of the
# standard development mnemonic ("${MNEMONIC}").
# Replace them before the network is used for anything other than local development.
accounts-allowlist = [
${accounts.map((account) => `  "${account}",`).join("\n")}
]
`,
);
console.log(`wrote ${count} accounts to ${target}`);
